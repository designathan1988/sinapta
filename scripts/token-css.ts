// Turns the four token trees into the generated stylesheet text.
import {
  aliasTarget,
  customPropertyName,
  flattenTokens,
  resolveType,
  type Token,
  type TokenError,
  type TokenMap,
} from "./token-tree.ts";
import { formatTokenValue } from "./token-value.ts";

export interface TokenSources {
  readonly base: unknown;
  readonly semantic: unknown;
  readonly light: unknown;
  readonly dark: unknown;
}

export type TokenCssResult =
  | { readonly ok: true; readonly css: string }
  | { readonly ok: false; readonly errors: readonly TokenError[] };

interface Themes {
  readonly light: TokenMap;
  readonly dark: TokenMap;
}

function formatOrError(token: Token, tokens: TokenMap): string | TokenError {
  const target = aliasTarget(token.value);
  if (target !== undefined && !tokens.has(target)) {
    return { path: token.path, message: `Unknown alias {${target}}.` };
  }
  const type = resolveType(token, tokens);
  if (typeof type !== "string") return type;
  const css = formatTokenValue(type, token.value);
  if (css !== undefined) return css;
  return { path: token.path, message: `Value does not fit type ${type}.` };
}

function themedValue(
  token: Token,
  themes: Themes,
  tokens: TokenMap,
): string | TokenError {
  const light = themes.light.get(token.path);
  const dark = themes.dark.get(token.path);
  if (light === undefined && dark === undefined) {
    return formatOrError(token, tokens);
  }
  if (light === undefined || dark === undefined) {
    return { path: token.path, message: "Token must be in both themes." };
  }
  const lightCss = formatOrError({ ...light, type: token.type }, tokens);
  if (typeof lightCss !== "string") return lightCss;
  const darkCss = formatOrError({ ...dark, type: token.type }, tokens);
  if (typeof darkCss !== "string") return darkCss;
  return `light-dark(${lightCss}, ${darkCss})`;
}

function orphanErrors(themes: Themes, tokens: TokenMap): TokenError[] {
  return [...themes.light.keys(), ...themes.dark.keys()]
    .filter((path) => !tokens.has(path))
    .map((path) => ({ path, message: "Theme token is not a semantic token." }));
}

function wrap(declarations: readonly string[]): string {
  return [
    "/* Generated by scripts/build-tokens.ts. Do not edit. */",
    "@layer tokens {",
    "  :root {",
    "    color-scheme: light dark;",
    ...declarations.map((line) => `    ${line}`),
    "  }",
    "",
    '  :root[data-theme="light"] {',
    "    color-scheme: light;",
    "  }",
    "",
    '  :root[data-theme="dark"] {',
    "    color-scheme: dark;",
    "  }",
    "}",
    "",
  ].join("\n");
}

export function buildTokenCss(sources: TokenSources): TokenCssResult {
  const tokens = new Map([
    ...flattenTokens(sources.base),
    ...flattenTokens(sources.semantic),
  ]);
  const themes: Themes = {
    light: flattenTokens(sources.light),
    dark: flattenTokens(sources.dark),
  };
  const errors = orphanErrors(themes, tokens);
  const declarations: string[] = [];
  for (const token of tokens.values()) {
    const value = themedValue(token, themes, tokens);
    if (typeof value === "string") {
      declarations.push(`${customPropertyName(token.path)}: ${value};`);
    } else {
      errors.push({
        path: value.path,
        message: "message" in value ? value.message : "",
      });
    }
  }
  return errors.length > 0
    ? { ok: false, errors }
    : { ok: true, css: wrap(declarations) };
}
